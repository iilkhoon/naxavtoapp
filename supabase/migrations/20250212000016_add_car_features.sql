-- Add RLS policies for features table
alter table public.car_features_options enable row level security;

create policy "Features are viewable by everyone."
  on public.car_features_options for select
  using ( true );

create policy "Admins can insert features."
  on public.car_features_options for insert
  with check ( auth.uid() in (select id from auth.users) ); -- Simplified for now

create policy "Admins can delete features."
  on public.car_features_options for delete
  using ( auth.uid() in (select id from auth.users) );
