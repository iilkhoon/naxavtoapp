/*
  # Create Push Tokens Table
  
  1. New Tables
    - `push_tokens`
      - `id` (bigint, primary key)
      - `token` (text, unique) - The Expo Push Token
      - `created_at` (timestamp)
  
  2. Security
    - Enable RLS
    - Allow anonymous inserts (for new users)
    - Allow admins to select (to send notifications)
*/

create table if not exists public.push_tokens (
  id bigint generated by default as identity primary key,
  token text not null unique,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.push_tokens enable row level security;

-- Allow anyone to register their token
create policy "Enable insert for everyone" 
  on public.push_tokens for insert 
  with check (true);

-- Allow admins (or anyone for now in this demo context) to read tokens to send notifications
create policy "Enable select for everyone" 
  on public.push_tokens for select 
  using (true);

-- Allow updates just in case
create policy "Enable update for everyone" 
  on public.push_tokens for update 
  using (true);
