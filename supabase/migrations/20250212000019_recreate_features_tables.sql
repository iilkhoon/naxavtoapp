-- 1. Reset tables (Clears all data as requested)
DROP TABLE IF EXISTS public.car_features;
DROP TABLE IF EXISTS public.fuel_types;

-- 2. Create car_features table
CREATE TABLE public.car_features (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. Create fuel_types table
CREATE TABLE public.fuel_types (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. Enable Security
ALTER TABLE public.car_features ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fuel_types ENABLE ROW LEVEL SECURITY;

-- 5. Create Policies (Public Read, Admin Write)
-- car_features policies
CREATE POLICY "Public read features" ON public.car_features 
  FOR SELECT USING (true);
CREATE POLICY "Admin all features" ON public.car_features 
  FOR ALL USING (auth.role() = 'authenticated');

-- fuel_types policies
CREATE POLICY "Public read fuel_types" ON public.fuel_types 
  FOR SELECT USING (true);
CREATE POLICY "Admin all fuel_types" ON public.fuel_types 
  FOR ALL USING (auth.role() = 'authenticated');

